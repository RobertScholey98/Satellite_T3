const git = (cwd: string, ...args: string[]) =>
  NodeChildProcess.execFileSync("git", args, { cwd, stdio: "pipe" }).toString();

/** A repository with one commit on main and its real path, as Revdoc keys Reviews by real path. */
export const makeRepository = () => {
  const root = NodeFS.realpathSync(NodeFS.mkdtempSync(NodePath.join(NodeOS.tmpdir(), "revdoc-")));
  git(root, "init", "-q", "-b", "main");
  git(root, "config", "user.email", "revdoc@example.com");
  git(root, "config", "user.name", "Revdoc");
  NodeFS.writeFileSync(NodePath.join(root, "README.md"), "base\n");
  git(root, "add", ".");
  git(root, "commit", "-q", "-m", "base");
  return root;
};

/** A second worktree of the repository on a new branch, by real path. */
export const addWorktree = (root: string, name: string) => {
  const path = NodePath.join(NodePath.dirname(root), `${NodePath.basename(root)}-${name}`);
  git(root, "worktree", "add", "-q", "-b", name, path);
  return NodeFS.realpathSync(path);
};

export const writeFile = (root: string, relative: string, content: string) => {
  NodeFS.mkdirSync(NodePath.dirname(NodePath.join(root, relative)), { recursive: true });
  NodeFS.writeFileSync(NodePath.join(root, relative), content);
};

export const readExport = (root: string) =>
  JSON.parse(NodeFS.readFileSync(NodePath.join(root, ".revdoc/review.json"), "utf8"));

/**
 * A stand-in review model. It proposes one check per changed file, keeps the id of a current
 * check that covers the same file, and returns combine portions unchanged.
 */
export const fakeReviewer = (prompt: string): GenerationOutput => {
  const data = JSON.parse(prompt.split("\n\n").at(-1)!);
  if (data.portion) {
    return {
      ...data.portion,
      items: data.portion.items.map((item: { id: string | null }) => ({
        ...item,
        id: item.id ?? "",
      })),
    };
  }
  const files = [
    ...new Set(
      [...String(data.changes).matchAll(/^(?:Untracked file: |diff --git a\/\S+ b\/)(\S+)/gm)].map(
        (match) => match[1]!,
      ),
    ),
  ];
  const current: Array<{ id: string; coveredPaths: string[] }> = data.currentChecks ?? [];
  return {
    title: "Review",
    summary: "Checks for the changed files.",
    context: "Generated by the test reviewer.",
    items: files.map((file) => ({
      id: current.find((check) => check.coveredPaths.includes(file))?.id ?? "",
      area: "Files",
      check: `Open ${file}`,
      expected: `${file} works`,
      coveredPaths: [file],
    })),
  };
};

export type Reviewer = (
  prompt: string,
  model: ModelSelection,
) => Effect.Effect<GenerationOutput, TextGenerationError>;

export const answering =
  (calls: Array<{ readonly prompt: string; readonly model: string }> = []): Reviewer =>
  (prompt, model) => {
    calls.push({ prompt, model: model.model });
    return Effect.succeed(fakeReviewer(prompt));
  };

export interface ThreadsDouble {
  /** Threads whose shell reports an active run, as an agent mid-turn would. */
  readonly live?: ReadonlyArray<ThreadId>;
  readonly runs?: (threadId: ThreadId) => ReadonlyArray<OrchestrationV2Run>;
  readonly subagents?: (threadId: ThreadId) => ReadonlyArray<unknown>;
  /** Top-level threads of the project; defaults to the parent thread alone. */
  readonly projectThreads?: ReadonlyArray<{ readonly id: ThreadId; readonly worktreePath: string }>;
  readonly dispatch?: ThreadManagement.ThreadManagementService["Service"]["dispatch"];
  readonly sendToThread?: ThreadManagement.ThreadManagementService["Service"]["sendToThread"];
}

const parentShell = (root: string, threadId = THREAD_ID) => ({
  ...liveThreadShell(threadId, { activeRunId: null }),
  projectId: PROJECT_ID,
  worktreePath: root,
});

export const layerRevdoc = <E = never>(input: {
  readonly root: string;
  readonly reviewer: { current: Reviewer };
  readonly threads?: ThreadsDouble;
  /** The real orchestration stack, in place of the thread double. */
  readonly threadManagement?: Layer.Layer<ThreadManagement.ThreadManagementService, E>;
  /** Collects the thread of every preview close. */
  readonly closedPreviews?: Array<ThreadId>;
  readonly settings?: Partial<ServerSettingsSchema>;
}) => {
  const threadDouble = Layer.mock(ThreadManagement.ThreadManagementService)({
    getThreadShell: (threadId) =>
      Effect.succeed({
        ...parentShell(input.root, threadId),
        ...(input.threads?.live?.includes(threadId)
          ? { activeRunId: RunId.make("run:active") }
          : {}),
        ...(threadId === CHILD_THREAD_ID
          ? {
              lineage: {
                rootThreadId: THREAD_ID,
                parentThreadId: THREAD_ID,
                relationshipToParent: "subagent" as const,
              },
            }
          : {}),
      }),
    getThreadRecords: ((threadId: ThreadId) =>
      Effect.succeed({
        thread: parentShell(input.root, threadId),
        messages: [],
        runs: input.threads?.runs?.(threadId) ?? [],
        subagents: input.threads?.subagents?.(threadId) ?? [],
      })) as never,
    getProjectThreadRecords: ((request: { readonly threadId: ThreadId }) =>
      Effect.succeed({ thread: parentShell(input.root, request.threadId) })) as never,
    listProjectThreads: () =>
      Effect.succeed(
        input.threads?.projectThreads?.map((thread) =>
          parentShell(thread.worktreePath, thread.id),
        ) ?? [parentShell(input.root)],
      ),
    getThreadEventSequence: () => Effect.succeed(0),
    streamStoredEventsFrom: () => Stream.empty as Stream.Stream<OrchestrationV2StoredEvent>,
    streamDomainEvents: Stream.never,
    dispatch: input.threads?.dispatch ?? (() => Effect.die("dispatch not expected")),
    sendToThread: input.threads?.sendToThread ?? (() => Effect.die("sendToThread not expected")),
  });
  const projects = Layer.mock(ProjectService.ProjectService)({
    getById: (id) =>
      Effect.succeed(
        Option.some({
          id,
          title: "Revdoc",
          workspaceRoot: input.root,
          defaultModelSelection: null,
          scripts: [],
          createdAt: "2026-01-01T00:00:00.000Z",
          updatedAt: "2026-01-01T00:00:00.000Z",
          deletedAt: null,
        } satisfies Project),
      ),
  });
  const textGeneration = Layer.mock(TextGeneration.TextGeneration)({
    generateStructured: ((request: { prompt: string; modelSelection: ModelSelection }) =>
      input.reviewer.current(request.prompt, request.modelSelection)) as never,
  });
  const previews = Layer.mock(PreviewManager.PreviewManager)({
    close: (request) => Effect.sync(() => void input.closedPreviews?.push(request.threadId)),
  });
  const threads = input.threadManagement ?? threadDouble;
  const gitDriver = GitVcsDriver.layer.pipe(
    Layer.provide(ServerConfig.layerTest(process.cwd(), { prefix: "revdoc-git-" })),
    Layer.provideMerge(VcsProcess.layer),
  );
  return RevdocService.layer.pipe(
    Layer.provideMerge(RevdocStore.layer),
    Layer.provideMerge(Layer.mergeAll(threads, projects, textGeneration, previews, gitDriver)),
    Layer.provideMerge(ServerSettings.layerTest(input.settings ?? {})),
    Layer.provideMerge(SqlitePersistence.layerMemory),
    Layer.provideMerge(NodeServices.layer),
  );
};

export const target = (overrides: Partial<RevdocTarget> = {}): RevdocTarget => ({
  threadId: THREAD_ID,
  ...overrides,
});

/** Waits for the pass's terminal state on the Review's own subscription stream. */
export const awaitPass = (passId: string, at: RevdocTarget = target()) =>
  Effect.flatMap(RevdocService.RevdocService, (revdoc) =>
    revdoc.subscribe(at).pipe(
      Stream.map((event: RevdocEvent): RevdocPass | undefined =>
        event._tag === "snapshot"
          ? event.snapshot.latestPasses.find((candidate) => candidate.id === passId)
          : event._tag === "delta" && event.latestPass?.id === passId
            ? event.latestPass
            : undefined,
      ),
      Stream.filter((pass): pass is RevdocPass => pass !== undefined),
      Stream.runHead,
      Effect.map(Option.getOrThrow),
    ),
  );

/** Waits until a running generation pass reports `completed` finished calls. */
export const awaitProgress = (passId: string, completed: number, at: RevdocTarget = target()) =>
  Effect.flatMap(RevdocService.RevdocService, (revdoc) =>
    revdoc.subscribe(at).pipe(
      Stream.filter((event) => {
        const pass =
          event._tag === "snapshot"
            ? event.snapshot.activePass
            : event._tag === "delta"
              ? event.activePass
              : null;
        return pass?.id === passId && (pass.generation?.completed ?? 0) >= completed;
      }),
      Stream.runHead,
      Effect.asVoid,
    ),
  );

const activeRun = (threadId: ThreadId, id = "run:active"): OrchestrationV2Run =>
  ({
    id: RunId.make(id),
    threadId,
    ordinal: 1,
    status: "running",
    rootNodeId: "node:root",
  }) as unknown as OrchestrationV2Run;

export const failingReviewer: Reviewer = () =>
  Effect.fail(new TextGenerationError({ operation: "generateStructured", detail: "quota" }));

const storedEvent = (event: unknown) =>
  ({ sequence: 1, commandId: null, event }) as OrchestrationV2StoredEvent;

/**
 * A parent mid-run. Its first delegated task request starts {@link CHILD_THREAD_ID}; each later
 * request starts a new child, as upstream derives the child from the command id.
 */
export const delegatingThreads = (): ThreadsDouble => {
  let delegations = 0;
  return {
    live: [THREAD_ID, CHILD_THREAD_ID],
    runs: (threadId) => (threadId === THREAD_ID ? [activeRun(THREAD_ID)] : []),
    dispatch: ((command: { readonly type: string }) => {
      if (command.type !== "delegated_task.request") {
        return Effect.succeed({ sequence: 1, storedEvents: [] });
      }
      delegations++;
      const childThreadId = ThreadId.make(
        delegations === 1 ? CHILD_THREAD_ID : `${CHILD_THREAD_ID}-${delegations}`,
      );
      return Effect.succeed({
        sequence: 1,
        storedEvents: [
          storedEvent({
            type: "subagent.updated",
            threadId: THREAD_ID,
            payload: { id: `node:task-${delegations}`, origin: "app_owned", childThreadId },
          }),
          storedEvent({
            type: "run.created",
            threadId: childThreadId,
            payload: { id: `run:child-${delegations}`, threadId: childThreadId, status: "running" },
          }),
        ],
      });
    }) as never,
  };
};
